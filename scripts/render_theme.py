def resolved_roles(palette: dict) -> dict[str, str]:
    colors = palette["colors"]
    return {name: colors[color_name] for name, color_name in palette["roles"].items()}


def without_hash(color: str) -> str:
    return color.removeprefix("#")


def alpha_hex(opacity: float) -> str:
    return f"{round(opacity * 255):02X}"


def hypr_rgba(color: str, opacity: float = 1.0) -> str:
    return f"rgba({without_hash(color)}{alpha_hex(opacity)})"


def rgb_triplet(color: str) -> str:
    value = without_hash(color)
    return ", ".join(str(int(value[index : index + 2], 16)) for index in (0, 2, 4))


def gtk_color(color: str) -> str:
    """Return a GTK CSS color, converting unsupported eight-digit hex values."""
    value = without_hash(color)
    if len(value) == 6:
        return color

    red, green, blue, alpha = (
        int(value[index : index + 2], 16) for index in (0, 2, 4, 6)
    )
    alpha_value = f"{alpha / 255:.3f}".rstrip("0").rstrip(".")
    return f"rgba({red}, {green}, {blue}, {alpha_value})"


def lua_bool(value: bool) -> str:
    return str(value).lower()


def render_hypr(palette: dict) -> str:
    colors = palette["colors"]
    roles = resolved_roles(palette)
    typography = palette["typography"]
    geometry = palette["geometry"]
    animation = palette["animation"]

    lines = [
        "-- Generated by scripts/render_theme.py from assets/nighthowler/palette.toml.",
        "-- Do not edit this file directly.",
        "",
        "return {",
        f'  name = "{palette["name"]}",',
        f'  slug = "{palette["slug"]}",',
        "  colors = {",
    ]

    for name, value in sorted(colors.items()):
        if name == "transparent":
            continue
        lines.append(f'    {name} = "rgba({without_hash(value)}ff)",')

    lines.extend(["  },", "  roles = {"])
    for name, value in sorted(roles.items()):
        lines.append(f'    {name} = "rgba({without_hash(value)}ff)",')

    lines.extend(
        [
            "  },",
            "  geometry = {",
            f"    border = {geometry['border_px']},",
            f"    rounding = {geometry['rounding_px']},",
            f"    gaps_in = {geometry['gap_inner_px']},",
            f"    gaps_out = {geometry['gap_outer_px']},",
            f"    opacity = {geometry['opacity']},",
            f"    blur_enabled = {lua_bool(geometry['blur_enabled'])},",
            f"    shadow_enabled = {lua_bool(geometry['shadow_enabled'])},",
            f"    shadow_range = {geometry['shadow_blur_px']},",
            f"    shadow_opacity = {geometry['shadow_opacity']},",
            f'    shadow_color = "rgba(000000{alpha_hex(geometry["shadow_opacity"])})",',
            "  },",
            "  animation = {",
            f"    fast_ds = {animation['duration_fast_ms'] / 100},",
            f"    normal_ds = {animation['duration_normal_ms'] / 100},",
            f"    slow_ds = {animation['duration_slow_ms'] / 100},",
            "  },",
            "  typography = {",
            f'    desktop = "{typography["desktop_font"]}",',
            f'    terminal = "{typography["terminal_font"]}",',
            f"    bar_size = {typography['bar_size_px']},",
            "  },",
            "  wallpaper = {",
            f'    relative_path = "assets/{palette["slug"]}/{palette["wallpaper"]["filename"]}",',
            f'    fit_mode = "{palette["wallpaper"]["fit"]}",',
            "  },",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


