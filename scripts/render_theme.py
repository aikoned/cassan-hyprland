def render_gtk_theme(palette: dict) -> str:
    colors = palette["colors"]
    roles = resolved_roles(palette)
    geometry = palette["geometry"]

    lines = [
        "/* Generated by scripts/render_theme.py from assets/nighthowler/palette.toml.",
        " * Do not edit this file directly.",
        " */",
        "",
    ]

    for name, value in sorted(colors.items()):
        css_name = name.replace("_", "-")
        lines.append(f"@define-color cassan-color-{css_name} {value};")

    lines.append("")
    for name, value in sorted(roles.items()):
        css_name = name.replace("_", "-")
        lines.append(f"@define-color cassan-{css_name} {value};")

    lines.extend(
        [
            f"@define-color cassan-shadow rgba(0, 0, 0, {geometry['shadow_opacity']});",
            "",
        ]
    )
    return "\n".join(lines)


