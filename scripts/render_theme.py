def render_wofi(palette: dict) -> str:
    """Render one self-contained stylesheet because Wofi loses import paths."""
    template = WOFI_STYLE_TEMPLATE.read_text(encoding="utf-8")
    if "@import" in template:
        raise ValueError("wofi/style.template.css must not contain relative imports")
    return render_gtk_theme(palette).rstrip() + "\n\n" + template


